#!/usr/bin/env node
/**
 * Deterministic converter: packed MSB 1-bit PNG/raw → C header for SSD1306.
 * Final artwork comes from the author (Illustrator). This tool only converts.
 *
 * Usage (when final PNG exists):
 *   node dev/tools/oled-mono-convert.mjs docs/assets/blueshift-oled-mono.png
 *
 * Without input: writes/validates placeholder header path only.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outHeader = join(root, "components/ui/oled_logo_generated.h");
const input = process.argv[2];

if (!input) {
  console.log("oled-mono-convert: no input — placeholder remains in oled_logo_placeholder.h");
  console.log("Provide author PNG/PBM when ready. Do not invent the final logo.");
  process.exit(0);
}

if (!existsSync(input)) {
  console.error("input missing:", input);
  process.exit(1);
}

// Minimal PBM P4 support for deterministic CI without image deps.
const buf = readFileSync(input);
if (buf[0] === 0x50 && buf[1] === 0x34) {
  // P4 binary PBM — parse width/height then bits.
  let i = 2;
  const skip = () => {
    while (i < buf.length && (buf[i] === 0x20 || buf[i] === 0x0a || buf[i] === 0x0d || buf[i] === 0x09)) i += 1;
    if (buf[i] === 0x23) {
      while (i < buf.length && buf[i] !== 0x0a) i += 1;
      skip();
    }
  };
  const readNum = () => {
    skip();
    let s = "";
    while (i < buf.length && buf[i] >= 0x30 && buf[i] <= 0x39) {
      s += String.fromCharCode(buf[i]);
      i += 1;
    }
    return Number(s);
  };
  const w = readNum();
  const h = readNum();
  skip();
  if (buf[i] === 0x0a) i += 1;
  const rowBytes = Math.ceil(w / 8);
  const bytes = [];
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < rowBytes; x += 1) {
      bytes.push(buf[i++]);
    }
  }
  const body = bytes.map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ");
  const hdr = `#pragma once
// GENERATED by oled-mono-convert.mjs — do not edit by hand.
namespace blueshift { namespace assets {
inline constexpr int kLogoGenW = ${w};
inline constexpr int kLogoGenH = ${h};
inline constexpr uint8_t kOledMonoGenerated[] = { ${body} };
} }
`;
  writeFileSync(outHeader, hdr);
  console.log("wrote", outHeader, w, "x", h);
  process.exit(0);
}

console.error("Unsupported format (use binary PBM P4 for dependency-free conversion)");
process.exit(1);
